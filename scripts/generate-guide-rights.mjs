#!/usr/bin/env node
/**
 * Generate the register of study guides by the rights status of their text:
 * public domain, or in copyright.
 *
 * WHY. Guided text games are built on a text's study guide, so the starting
 * point for "does this text have guided games" is the set of guides, and the
 * `rights.status` each guide file declares decides how its path is held to the
 * fair-dealing limits (src/lib/games/text-games/quoted.ts).
 * src/lib/games/text-games/slugs.ts then leaves out any text that has no games
 * all the same.
 *
 * Until 10 October 2026 this generated the public-domain half only, because a
 * text in copyright had no games: the reasoning was that a game quotes and
 * re-arranges a text far more freely than a guide does. Measured that day, it
 * does not. A path is built only from its guide's own quotations, so it quotes
 * a subset of what the guide page already quotes within the limits; for all 71
 * guides of texts in copyright the path quoted less than its guide, and no
 * single quotation ran over 14 words. So texts in copyright have paths too,
 * each measured on every test run and again whenever one is built.
 *
 * Reading that at runtime means loading the guide, and a guide is tens of
 * kilobytes that the header, the revision rail and the games hub have no other
 * use for. The answer is a fact about the directory, so it is generated from the
 * directory, the same way src/data/study-guides/index.ts is.
 *
 * It cannot drift silently: text-games-are-offered-only-where-they-exist.test.ts
 * loads every guide and fails, in both directions, if this register disagrees
 * with what the guides say. Re-run this script when a guide is added or its
 * rights change.
 *
 * Deterministic and read-only apart from its one output file. Touches no
 * database and no network.
 *
 *   node scripts/generate-guide-rights.mjs
 */

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = process.cwd()
const DIR = join(ROOT, 'src/data/study-guides')
const OUT = join(ROOT, 'src/lib/study-guides/guide-rights.generated.ts')

/** Every guide file declares `rights: { status: ... }` in this shape. */
const RIGHTS = /\brights:\s*\{\s*status:\s*'(public-domain|copyright)'/

const slugs = readdirSync(DIR)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .map((f) => f.replace(/\.ts$/, ''))
  .filter((s) => /^[a-z0-9-]+$/.test(s))
  .sort()

const publicDomain = []
const copyright = []
for (const slug of slugs) {
  const match = RIGHTS.exec(readFileSync(join(DIR, `${slug}.ts`), 'utf8'))
  // A guide whose rights cannot be read is put in neither set. Failing here is
  // the point: the alternative is a register that quietly leaves a text out,
  // or quietly holds a text in copyright to no limits at all.
  if (!match) {
    console.error(`${slug}.ts declares no rights.status this script can read`)
    process.exit(1)
  }
  ;(match[1] === 'public-domain' ? publicDomain : copyright).push(slug)
}

const set = (name, doc, list) => `/**
${doc}
 */
export const ${name}: ReadonlySet<string> = new Set([
${list.map((s) => `  '${s}',`).join('\n')}
])
`

const body = `// AUTO-GENERATED by scripts/generate-guide-rights.mjs - do not edit by hand.
// Re-run that script after adding a study guide or changing a guide's rights.

${set(
  'PUBLIC_DOMAIN_GUIDE_SLUGS',
  ` * Study guides whose text is in the public domain, read from each guide's own
 * \`rights.status\` in src/data/study-guides. A statement about rights only:
 * which texts have guided games is decided in src/lib/games/text-games/slugs.ts.`,
  publicDomain,
)}
${set(
  'COPYRIGHT_GUIDE_SLUGS',
  ` * Study guides whose text is in copyright, read the same way. Their quotations
 * are held to the limits in src/lib/study-guides/fair-dealing.ts, on the guide
 * page and in the text's guided games alike.`,
  copyright,
)}`

const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
if (current !== body) writeFileSync(OUT, body, 'utf8')
console.log(
  `guides: ${publicDomain.length} public domain and ${copyright.length} in copyright, of ${slugs.length}, written to ${OUT.replace(ROOT, '.')}`,
)
