#!/usr/bin/env node
/**
 * Generate the register of study guides whose text is in the public domain.
 *
 * WHY. Guided text games are built on a text's study guide, and only on guides
 * of public-domain texts: a game quotes and re-arranges the text far more freely
 * than a guide does, which the fair-dealing limits on a text in copyright do not
 * allow. So the starting point for "does this text have guided games" is the
 * `rights.status` each guide file declares; src/lib/games/text-games/slugs.ts
 * then leaves out any public-domain text that has no games all the same.
 *
 * Reading that at runtime means loading the guide, and a guide is tens of
 * kilobytes that the header, the revision rail and the games hub have no other
 * use for. The answer is a fact about the directory, so it is generated from the
 * directory, the same way src/data/study-guides/index.ts is.
 *
 * It cannot drift silently: text-games-are-offered-only-where-they-exist.test.ts
 * loads every guide and fails, in both directions, if this register disagrees
 * with what the guides say. Re-run this script when a guide is added or its
 * rights change.
 *
 * Deterministic and read-only apart from its one output file. Touches no
 * database and no network.
 *
 *   node scripts/generate-public-domain-guides.mjs
 */

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = process.cwd()
const DIR = join(ROOT, 'src/data/study-guides')
const OUT = join(ROOT, 'src/lib/study-guides/public-domain.generated.ts')

/** Every guide file declares `rights: { status: ... }` in this shape. */
const RIGHTS = /\brights:\s*\{\s*status:\s*'(public-domain|copyright)'/

const slugs = readdirSync(DIR)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .map((f) => f.replace(/\.ts$/, ''))
  .filter((s) => /^[a-z0-9-]+$/.test(s))
  .sort()

const publicDomain = []
for (const slug of slugs) {
  const match = RIGHTS.exec(readFileSync(join(DIR, `${slug}.ts`), 'utf8'))
  // A guide whose rights cannot be read is not assumed to be public domain.
  // Failing here is the point: the alternative is a register that quietly
  // leaves a text out, or quietly lets one in.
  if (!match) {
    console.error(`${slug}.ts declares no rights.status this script can read`)
    process.exit(1)
  }
  if (match[1] === 'public-domain') publicDomain.push(slug)
}

const body = `// AUTO-GENERATED by scripts/generate-public-domain-guides.mjs - do not edit by hand.
// Re-run that script after adding a study guide or changing a guide's rights.

/**
 * Study guides whose text is in the public domain, read from each guide's own
 * \`rights.status\` in src/data/study-guides. A statement about rights only:
 * which of these have guided games is decided in
 * src/lib/games/text-games/slugs.ts.
 */
export const PUBLIC_DOMAIN_GUIDE_SLUGS: ReadonlySet<string> = new Set([
${publicDomain.map((s) => `  '${s}',`).join('\n')}
])
`

const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
if (current !== body) writeFileSync(OUT, body, 'utf8')
console.log(
  `public-domain guides: ${publicDomain.length} of ${slugs.length} written to ${OUT.replace(ROOT, '.')}`,
)
