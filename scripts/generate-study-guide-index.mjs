#!/usr/bin/env node
/**
 * Generate src/data/study-guides/index.ts from the guide files beside it.
 *
 * WHY GENERATED. The register is a map of lazy imports, one per guide file. A
 * hand-kept map drifts the first time a guide is added and not registered, and
 * that failure is silent: the guide exists, passes its checks, and no page ever
 * loads it. Scanning the directory makes the register a fact about the
 * directory. study-guides.test.ts asserts the two agree, so a stale commit
 * fails the suite.
 *
 * Deterministic: the same directory always produces the same bytes, so running
 * it twice, or from two places at once, cannot produce a wrong file.
 *
 *   node scripts/generate-study-guide-index.mjs
 */

import { readdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const DIR = join(process.cwd(), 'src/data/study-guides')
const OUT = join(DIR, 'index.ts')

const slugs = readdirSync(DIR)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .map((f) => f.replace(/\.ts$/, ''))
  .filter((s) => /^[a-z0-9-]+$/.test(s))
  .sort()

const body = `// AUTO-GENERATED by scripts/generate-study-guide-index.mjs - do not edit by hand.
// Re-run that script after adding or removing a guide in this directory.

/**
 * The register of study-guide files. One lazy loader per text, keyed by the
 * set-text slug in src/lib/board/set-texts.ts. Lazy so that a page loads the one
 * guide it renders; see src/lib/study-guides/load.ts.
 */

import type { StudyGuide } from '@/lib/study-guides/types'

export const STUDY_GUIDE_LOADERS: Record<string, () => Promise<StudyGuide>> = {
${slugs.map((s) => `  '${s}': () => import('./${s}').then((m) => m.guide),`).join('\n')}
}
`

const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
if (current !== body) writeFileSync(OUT, body)
console.log(`study-guide index: ${slugs.length} guide${slugs.length === 1 ? '' : 's'}`)
