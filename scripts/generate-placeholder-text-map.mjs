#!/usr/bin/env node
/**
 * Generate the register of set texts whose page is a placeholder.
 *
 * WHY. Three different things look the same from outside: a text with a full
 * multi-section guide, a text with one real page and no sub-pages, and a text
 * whose page renders `StubStudyGuide` and says "study guide in production".
 * Much Ado About Nothing and Explorers, or boys messing about? both have a
 * `page.tsx` and no sub-pages; one is 54 KB of guide and the other is 891 bytes
 * of apology.
 *
 * The board shelf has to tell a student which is which, and it must not lie.
 * Hand-maintaining a list of twenty slugs is how the tile grid this replaces
 * ended up declaring 172 routes against 93 real ones, so this is derived from
 * the filesystem on every prebuild instead, exactly like
 * generate-text-subpage-map.mjs.
 *
 * Read-only. Touches no database and no network.
 *
 *   node scripts/generate-placeholder-text-map.mjs
 */

import { readdirSync, readFileSync, existsSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = process.cwd()
const TEXTS_DIR = join(ROOT, 'src/app/revision/texts')
const OUT = join(ROOT, 'src/lib/revision/placeholder-texts.generated.ts')

/** The component a placeholder page renders. One marker, checked in one place. */
const MARKER = 'StubStudyGuide'

function findPlaceholders() {
  if (!existsSync(TEXTS_DIR)) return []
  const slugs = []
  for (const entry of readdirSync(TEXTS_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    if (entry.name.startsWith('_') || entry.name.startsWith('[')) continue
    const page = join(TEXTS_DIR, entry.name, 'page.tsx')
    if (!existsSync(page)) continue
    if (readFileSync(page, 'utf8').includes(MARKER)) slugs.push(entry.name)
  }
  return slugs.sort()
}

const slugs = findPlaceholders()

const body = `// AUTO-GENERATED by scripts/generate-placeholder-text-map.mjs - do not edit by hand.
// Re-run that script after adding or removing a study guide under
// src/app/revision/texts. It runs in \`npm run prebuild\`.

/**
 * Set texts whose page renders the "study guide in production" placeholder.
 *
 * Distinct from STUB_SET_TEXT_SLUGS in src/lib/seo/set-text-stubs.ts, which
 * lists the texts that have no directory at all and fall through to the
 * catch-all route. A text can be in one, the other, or neither.
 */
export const PLACEHOLDER_TEXT_SLUGS: ReadonlySet<string> = new Set([
${slugs.map((s) => `  '${s}',`).join('\n')}
])
`

writeFileSync(OUT, body, 'utf8')
console.log(`placeholder texts: ${slugs.length} written to ${OUT.replace(ROOT, '.')}`)
