// Generates src/lib/revision/text-subpages.generated.ts - the set of
// /revision/texts/<text>/<subpage> routes that actually have a page.tsx.
// TextStudyHub (a client component, so no fs access) filters its sub-page
// tiles against this set so we never link to a subpage that does not exist.
// Re-run after adding or removing a text subpage:
//   node scripts/generate-text-subpage-map.mjs
import { readdirSync, statSync, existsSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const textsDir = join(root, 'src', 'app', 'revision', 'texts')

const routes = []
for (const text of readdirSync(textsDir).sort()) {
  if (text.startsWith('[') || text.startsWith('_')) continue
  const textDir = join(textsDir, text)
  if (!statSync(textDir).isDirectory()) continue
  for (const sub of readdirSync(textDir).sort()) {
    const subDir = join(textDir, sub)
    if (!statSync(subDir).isDirectory()) continue
    if (existsSync(join(subDir, 'page.tsx'))) {
      routes.push(`/revision/texts/${text}/${sub}`)
    }
  }
}

const out = `// AUTO-GENERATED by scripts/generate-text-subpage-map.mjs - do not edit by hand.
// Re-run that script after adding or removing a subpage under src/app/revision/texts.

/** Every /revision/texts/<text>/<subpage> route with an existing page.tsx. */
export const TEXT_SUBPAGE_ROUTES: ReadonlySet<string> = new Set([
${routes.map((r) => `  '${r}',`).join('\n')}
])
`

const outPath = join(root, 'src', 'lib', 'revision', 'text-subpages.generated.ts')
writeFileSync(outPath, out)
console.log(`Wrote ${routes.length} routes to ${outPath}`)
