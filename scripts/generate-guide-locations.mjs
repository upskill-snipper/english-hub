#!/usr/bin/env node
/**
 * Generate the register of set-text guides that do not live under
 * src/app/revision/texts.
 *
 * WHY THIS EXISTS. The board shelf built every card's link as
 * `/revision/texts/<slug>`, because that is where a set text's guide is
 * supposed to be. For twenty-eight of the seventy-three set texts it is not.
 * They are spread across four other trees, 344 to 1,491 lines each, while their
 * /revision/texts page is a placeholder or absent entirely.
 *
 * So choosing a board and clicking, say, Disabled sent the student past an
 * 856-line guide to a page that does not exist, and the shelf labelled the card
 * "no guide yet" on the way. Antony and Cleopatra (1,491 lines), A Doll's House
 * (1,315) and The Handmaid's Tale (1,116) were unreachable the same way. The
 * work was written, paid for and invisible.
 *
 * WHY THE BOARD IS RECORDED. War Photographer has two guides: the Edexcel IGCSE
 * one under /igcse/edexcel/poetry and the AQA Power and Conflict cluster one
 * under /revision/poetry/power-and-conflict, which reads it against the rest of
 * that anthology. Picking by length would send every AQA student to the shorter
 * Edexcel page. The shelf knows which board it is drawing, so the register
 * carries the board each guide was written for and lets the caller match.
 *
 * WHY IT IS GENERATED RATHER THAN WRITTEN DOWN. The same reason as
 * generate-placeholder-text-map.mjs: a hand-kept list of twenty-eight slugs drifts
 * the first time someone moves a directory, and the failure is silent - a link
 * to a page that 404s, or a guide that quietly stops being advertised. Scanning
 * the filesystem on every prebuild means a guide that moves is re-registered and
 * a guide that is deleted stops being claimed.
 *
 * WHAT IT DELIBERATELY DOES NOT DO. It does not rank. If a text has a real page
 * under /revision/texts, that page wins and this register is not consulted - the
 * canonical location stays canonical. This only answers "and if it does not?".
 *
 * Read-only. Touches no database and no network.
 *
 *   node scripts/generate-guide-locations.mjs
 */

import { readdirSync, readFileSync, existsSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = process.cwd()
const OUT = join(ROOT, 'src/lib/revision/guide-locations.generated.ts')

/** The component a placeholder page renders. Never register one of these. */
const MARKER = 'StubStudyGuide'

/**
 * Where else a set text's guide may live, searched in this order.
 *
 * `dir` is scanned for directories containing a page.tsx; `route` is the URL
 * prefix, stated explicitly so a route that does not mirror its directory
 * cannot be inferred wrongly. `board` is the specification the guide was
 * written against, or null when it is board-neutral.
 *
 * The order is the tie-break when no board matches: board-specific trees first,
 * then the general revision-notes library.
 */
const TREES = [
  {
    dir: 'src/app/igcse/edexcel-lang/anthology',
    route: '/igcse/edexcel-lang/anthology',
    board: 'edexcel-igcse-lang',
  },
  { dir: 'src/app/igcse/edexcel/poetry', route: '/igcse/edexcel/poetry', board: 'edexcel-igcse' },
  {
    dir: 'src/app/revision/poetry/power-and-conflict',
    route: '/revision/poetry/power-and-conflict',
    board: 'aqa',
  },
  { dir: 'src/app/resources/revision-notes', route: '/resources/revision-notes', board: null },
]

function guidesIn(tree) {
  const abs = join(ROOT, tree.dir)
  if (!existsSync(abs)) return []
  const found = []
  for (const entry of readdirSync(abs, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    if (entry.name.startsWith('_') || entry.name.startsWith('[')) continue
    const page = join(abs, entry.name, 'page.tsx')
    if (!existsSync(page)) continue
    const src = readFileSync(page, 'utf8')
    // An apology is not a guide. Registering one would route a student away
    // from /revision/texts to an identical apology on a longer URL.
    if (src.includes(MARKER)) continue
    found.push({
      slug: entry.name,
      href: `${tree.route}/${entry.name}`,
      board: tree.board,
      lines: src.split('\n').length,
    })
  }
  return found
}

/** Every guide for a slug, in tree order. The caller picks by board. */
const map = new Map()
for (const tree of TREES) {
  for (const guide of guidesIn(tree)) {
    if (!map.has(guide.slug)) map.set(guide.slug, [])
    map.get(guide.slug).push(guide)
  }
}

const slugs = [...map.keys()].sort()
const total = slugs.reduce((n, s) => n + map.get(s).length, 0)

const entries = slugs
  .map((slug) => {
    const list = map
      .get(slug)
      .map((g) => `{ href: '${g.href}', board: ${g.board ? `'${g.board}'` : 'null'} }`)
      .join(', ')
    return `  ['${slug}', [${list}]],`
  })
  .join('\n')

const body = `// AUTO-GENERATED by scripts/generate-guide-locations.mjs - do not edit by hand.
// Re-run that script after adding, moving or removing a study guide outside
// src/app/revision/texts. It runs in \`npm run prebuild\`.

/** One guide, and the specification it was written against. */
export interface GuideLocation {
  href: string
  /** The board this guide targets, or null when it is board-neutral. */
  board: string | null
}

/**
 * Set-text guides that live somewhere other than /revision/texts/<slug>.
 *
 * Consulted only when a text has no real page of its own, so a text with a
 * guide in both places keeps its canonical URL. A slug can have more than one -
 * War Photographer has an Edexcel IGCSE guide and an AQA Power and Conflict
 * guide - so the caller matches on board. See the generator's docblock for why
 * twenty-eight guides were unreachable before this existed.
 */
export const GUIDE_LOCATIONS: ReadonlyMap<string, readonly GuideLocation[]> = new Map([
${entries}
])
`

writeFileSync(OUT, body, 'utf8')
console.log(
  `guide locations: ${total} guides for ${slugs.length} texts written to ${OUT.replace(ROOT, '.')}`,
)
