/**
 * What a question asks. Absent: what the phrasal verb shown means, keyed by
 * the phrasal verb, as the first 58 questions always were.
 *
 *   sense     what the phrasal verb shown means in this sentence, where it
 *             has another meaning elsewhere; keyed by the sentence;
 *   opposite  which phrasal verb means the opposite of the one shown, in the
 *             sense the sentence gives it; keyed by the sentence;
 *   gap       which phrasal verb fills the gap ("___"); the phrasal verb is
 *             not shown; keyed by the sentence.
 */
export type PhrasalKind = 'sense' | 'opposite' | 'gap'

export interface PhrasalVerb {
  /** The phrasal verb the question is about, in its base form. A gap's answer, unshown. */
  phrasal: string
  /** The sentence shown with it. In a gap question, "___" marks the gap. */
  sentence: string
  /**
   * The right option as the student sees it: a meaning, or for a gap or an
   * opposite the phrasal verb itself, in the form the sentence needs.
   */
  meaning: string
  distractors: [string, string, string]
  /** 1 A1, 2 A2, 3 B1 (GameBank.tier): everyday and literal, then less literal, then in context. */
  tier: 1 | 2 | 3
  /**
   * What the phrasal verb means here, as a group of near neighbours ("wait"
   * for hold on and hang on): no two questions of one meaning are dealt in a
   * round, so one never gives the other away.
   */
  means: string
  kind?: PhrasalKind
  /** Lines shown before the sentence: the turn before it in a dialogue, or a short text. */
  context?: string[]
  /** Where a real line comes from: a held public-domain text, as printed. */
  source?: string
  /**
   * Other phrasal verbs, in the base form, that this question's answer or
   * explanation names: an opposite's answer, a neighbour it is taught beside.
   */
  also?: string[]
}

