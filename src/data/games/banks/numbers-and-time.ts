export type ItemType = 'cardinal' | 'ordinal' | 'clock' | 'date'

export interface NumberItem {
  /** What the learner reads / sees as the prompt */
  prompt: string
  /** Short instruction shown above the prompt */
  task: string
  /**
   * Shown between the instruction and the prompt, in ordinary type: a price
   * list, a timetable, or a real line with its source on the last line.
   */
  context?: string
  /** The correct answer (must also appear in options) */
  answer: string
  /** Distractor answers - must be plausible and the same shape as the answer */
  distractors: string[]
  type: ItemType
  /** 1 recall and recognition (A1), 2 understanding (A2), 3 using it in context (B1). */
  tier: 1 | 2 | 3
  /**
   * What would give this question away to another in the same round: the
   * number it is about, the pair a learner mixes up (13 and 30), the rule its
   * explanation teaches, or the timetable it reads (BANK.facts).
   */
  facts?: string[]
}

