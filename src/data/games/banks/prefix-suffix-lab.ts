import type { GameBank } from '@/lib/games/explanations/types'

/**
 * Prefix & Suffix Lab: build, spell and read words made with prefixes and
 * suffixes. A build question gives a root and a goal ("NOT happy", "the act of
 * educating") and four affixes; a sentence question gives a sentence to
 * complete, often a real line from a set text, and four words; a reading
 * question gives a real line and asks what an affixed word does in it.
 *
 * Moved out of src/app/games/prefix-suffix-lab/page.tsx on 16 October 2026, when
 * every answer gained an explanation (src/lib/games/explanations/types.ts). The
 * page had two banks, 47 prefix questions and 48 suffix questions. They are now
 * one list, each question saying which it is (`mode`), and the page derives its
 * two banks from it.
 *
 * WHAT WAS WRONG WITH THE QUESTIONS (found writing those explanations). The three
 * wrong affixes are dealt at random from the pool, so a question is only fair if
 * no other affix in the pool also builds a word that fits the goal as written,
 * and a goal has to be true, and clear, for the people who read it. Ten questions
 * failed that test, and one note taught a false rule:
 *
 *   - lock, "meaning: to OPEN a lock again": the goal wants un- (unlock), but
 *     "again" is what re- means (relock), so it pointed at a wrong option. It now
 *     reads "meaning: to OPEN a lock";
 *   - like, "meaning: to NOT like": un- builds unlike, which literally means "not
 *     like", beside dis- (dislike), and online to unlike a post is a verb too. It
 *     now reads "meaning: to feel you do NOT like something";
 *   - cover, "meaning: to take a cover OFF / reveal", was marked dis- (discover).
 *     That goal describes uncover, and un- was among the wrong options in about 3
 *     deals in 7. The question now asks for un-: the answer is un-, the word is
 *     uncover, the goal is "meaning: to take a cover OFF" and the note is
 *     rewritten. The affix tally becomes un- 7 and dis- 5;
 *   - place, "meaning: to put in the WRONG place": dis- builds displace, which a
 *     careful student could defend. It now ends "and lose it", which is misplace;
 *   - use (suffix), "make an ADJECTIVE meaning of use": -able builds usable, which
 *     also fits "of use". It now reads "full of use", as the other -ful goals say
 *     "full of";
 *   - beauty (suffix), "full of beauty": -ous builds beauteous, a poetic word that
 *     Shakespeare uses and that students meet in The Tempest, so a student could
 *     defend it. The question now uses mercy, "full of mercy", which has the same
 *     y-to-i spelling change, and only -ful in the pool builds a word with that
 *     meaning: merciful (-less builds merciless, its opposite);
 *   - way, "meaning: a railway UNDER the ground": that is the American and Glasgow
 *     sense. A British subway is usually a path under a road, so the goal now
 *     reads "a path or railway UNDER the ground";
 *   - city, "meaning: a road running BETWEEN cities": intercity is an adjective,
 *     chiefly for trains and coaches, not a noun for a road. It now reads
 *     "meaning: travelling BETWEEN cities";
 *   - connected, "meaning: linked BETWEEN each other", and govern, "make a NOUN for
 *     the body that governs", were hard to read: "between each other" is not
 *     standard English, and a child can read "body" as a human body. They now
 *     read "meaning: with links BETWEEN all the parts" and "make a NOUN for the
 *     group of people who govern";
 *   - gentle, the note said "Drop e: gentle becomes gently". Dropping the e would
 *     give gentlly. The -le changes to -ly, and the note now says so.
 *
 * Every other goal, root and answer is unchanged. The old one-line notes
 * (`meaningNote`) are kept in the data but no longer shown: the explanation
 * after each answer covers them.
 *
 * REBUILT FOR DEPTH (24 October 2026). The founder found the games "too
 * obvious and easy". Measured that day (.tmp-games-audit/REPORT-ks3.md), a
 * student who knew thirteen one-word meanings ("NOT" is un-, "AGAIN" is re-)
 * scored 88 per cent, and "make an ADVERB" could be dealt with one adverb
 * suffix among its four. Every question now has a tier and its own wrong
 * options, and the bank grew from 95 questions to 267:
 *
 *   - tier 2: which "not" prefix a word takes, in a sentence with no hint
 *     (il-, im-, ir-, in- or un-), and letters at the join (unnecessary,
 *     dissatisfied), each wrong option a mistake people make;
 *   - tier 2: spelling where a suffix joins (y to i, dropping or keeping the
 *     e, doubling, -able or -ible, -ance or -ence), and which form of a word a
 *     sentence needs, the word class unnamed;
 *   - tiers 1 and 2: prefixes and suffixes the bank never taught (trans-,
 *     tele-, fore-, auto-, -hood, -ship, -ify, -ise and others), and words
 *     whose prefixes make them near neighbours (disarmed or unarmed, imports
 *     or exports, disinterested or uninterested);
 *   - tier 3: what an affix does to a word in a real line of a set text, and
 *     why the writer chose it ("unhallowed", "tolerable", "most unkindest").
 *
 * Every real line is copied from src/data/full-texts/, and `source` says
 * where it comes from; an invented sentence has no source. Where the edition
 * prints a word in italics it is kept as the edition marks it ("tempt _me_"),
 * and the page shows it in italics (a-game-real-line-is-the-held-text.test.ts
 * holds each line to the text, italics marks included).
 *
 * WHAT CHANGED IN THE OLD QUESTIONS. All but one of the 95 are kept, each with
 * three fixed wrong options chosen as near neighbours (reuse beside misuse,
 * disuse and abuse) in place of three dealt at random. The suffix goals no
 * longer name a word class ("make an ADJECTIVE meaning “full of care”" now
 * reads "meaning: “full of care”"), so their keys changed, and the inform goal
 * now reads "the facts that inform you". Removed: careful + -ly, because its
 * root is another question's answer (care + -ful makes careful).
 *
 * WHAT IS KEPT APART. One root a round, as before. `shared` names anything else
 * two questions have in common that would give one away: one quotation or
 * poem, or a rule that one explanation teaches and another question tests.
 *
 * CHECKED (31 October 2026), by a second reader, every question against its
 * text: all 146 real lines are the held text in the chapter, act or scene
 * `source` names, with the right word in the gap. What was fixed:
 *
 *   - disinterested, invaluable, amoral: tier 3, but choosing between near
 *     neighbours is tier 2, as this docblock says above; now tier 2;
 *   - inconstant: "It shines only on the rich" was a joke, not a misreading;
 *     now the moon is envious, as Romeo has just called it;
 *   - greatness: "the same as being tall" was a joke; now -ness turning great
 *     into an adverb, a word-class mistake like the verb option beside it;
 *   - fearful: "like a kitten that loves to be stroked" was a joke; now the
 *     maker is anxious, a misreading of whose fear it is;
 *   - brevity: "too sad to speak" fitted nothing; now mocking Hamlet;
 *   - multitudinous: "the seas are tiny" was absurd; now the seas are already
 *     red, which "Making the green one red" rules out;
 *   - Ignorance: "forgotten his name" was absurd; now Scrooge as a child, the
 *     first Ghost's lesson;
 *   - breathless: one wrong option said "finally finished at last";
 *   - amazed, depth, warmth: invented sentences, now real lines that test the
 *     same thing (Animal Farm 5 and 2, Frankenstein 12);
 *   - kept apart that were not: the two If questions, the two from Lady
 *     Macbeth's speech in 1.5, the two on Lanyon and Jekyll, the two
 *     "detestable" lines, humorous and odorous (the u drops before -ous);
 *   - kept apart by the rule an explanation teaches and another tests:
 *     keeping or dropping e, e after a soft c or g, y to i, doubling, letters
 *     at a prefix join and at a suffix join, un- before an English word, and
 *     each form in- takes (il-, ir-, im-, in-), so that no explanation in a
 *     round answers a later question's spelling.
 */

export type LabMode = 'prefix' | 'suffix'

export interface LabSeed {
  mode: LabMode
  /** The base/root word: shown to the learner in a build question, and the question's fact (one root a round) */
  root: string
  /** What the learner is aiming for (a build question's goal), or what a sentence question asks */
  target: string
  /** The correct option: an affix, a whole word or a reading */
  answer: string
  /** The finished word once the affix is attached */
  resultingWord: string
  /** A short teaching note (UK English morphology), kept in the data but no longer shown */
  meaningNote?: string
  /** 1 recall, 2 understanding, 3 the exam skill (24 October 2026) */
  tier: 1 | 2 | 3
  /** The wrong options shown with the answer, each a near neighbour or a real mistake (24 October 2026) */
  wrong: readonly string[]
  /** A sentence to complete, with ___ for the gap, or a line to read, in place of the root and goal */
  sentence?: string
  /** Where a real sentence comes from: the text and its chapter, act or stanza */
  source?: string
  /** The affix the question turns on, where the answer is a word or a reading */
  affix?: string
  /** The rule a round deals at most two of, where it is not the affix */
  skill?: string
  /** The word family, where it is not the root, for the dealer's facts */
  family?: string
  /**
   * Something two questions share that would give one away to the other: one
   * quotation, one poem, or one rule explained in both. They are never dealt
   * together.
   */
  shared?: string | readonly string[]
}

/** A question's shared facts as a list, whether it names one or several. */
const sharedOf = (q: LabSeed): readonly string[] =>
  q.shared === undefined ? [] : typeof q.shared === 'string' ? [q.shared] : q.shared

