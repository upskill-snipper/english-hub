/**
 * Everyday Vocabulary Flashcards: see an everyday English word with an example
 * sentence, turn the card to check its meaning and see the word in a second
 * sentence, then say whether you knew it.
 *
 * Moved out of src/app/games/everyday-vocab-flashcards/page.tsx on 16 October
 * 2026, when every answer gained an explanation
 * (src/lib/games/explanations/types.ts).
 *
 * A card is one word. The student turns it over and marks it themselves, so no
 * card has options (options is null, and an explanation has no "not"), the
 * "right answer" is the meaning on the back, and a mark of "I knew it" is
 * recorded as correct. The explanation is shown with the back of the card.
 *
 * WHAT WAS WRONG WITH THE CARDS (found writing those explanations). Five of the
 * 64 had a fault; the other 59 are unchanged.
 *   - home is a noun on the card, but its example was "I go home after work.",
 *     where home is an adverb. It is now "Our home is near the park."
 *   - early is an adjective on the card, but its example was "I woke up early to
 *     catch the bus.", where early is an adverb. It is now "I caught the early
 *     bus to school."
 *   - sleep was defined as resting "at night", and its own example is about babies
 *     sleeping "during the day". It is now "To rest with your eyes closed,
 *     usually at night."
 *   - angry was defined as "Feeling strong displeasure." Displeasure is a far
 *     harder word than the A1 word it explains. It is now "Feeling that you want
 *     to shout, because something is wrong or unfair."
 *   - bored was defined as "Feeling tired because something is not interesting."
 *     Being bored is not being tired, and tired is a card of its own. It is now
 *     "Feeling unhappy because something is not interesting."
 *
 * REBUILT FOR DEPTH ON 24 OCTOBER 2026. The deck was 64 cards in six topics,
 * with no level, and the back of a card repeated the sentence on its front. It
 * is now 240 cards, 80 at each level:
 *
 *   tier 1, A1   the words of home, school, shops, travel and the body
 *                (bed, ticket, cheap, hungry), and 49 of the first 64;
 *   tier 2, A2   neighbour, angry, worried and the other eight A2 words of the
 *                first 64, and 69 more (queue, platform, headache, interview,
 *                lonely);
 *   tier 3, B1   colleague, stranger, proud and calm, and 76 more (receipt,
 *                deadline, prescription, salary, embarrassed).
 *
 * Six topics a learner needs were added beside the first six: Home, School,
 * Shops, Travel, Health and Work; the new feelings words join Feelings. Every
 * card's back now shows the word in a second sentence (`sentence`), so the
 * student checks the meaning in a new place, not the one they just read. On
 * 35 cards that sentence is a real line from a held public-domain book,
 * copied word for word with the chapter in `source` ("By the autumn the
 * animals were tired but happy.", Animal Farm), chosen only where the line is
 * short and plain and uses the word in the card's own meaning; the field is
 * named `sentence` so that src/__tests__/a-game-real-line-is-the-held-text.test.ts
 * holds it. Every other sentence is the site's own.
 *
 * The first 64 keep their words (the key), meanings, front sentences and
 * topics, and nothing was removed; each gained a level and a back sentence.
 *
 * HOW A CARD IS MARKED, SCORED AND SAVED IS UNCHANGED (the founder's decision):
 * a self-check, saved as right when the student taps "I knew it". Because a
 * self-check earns no level (src/lib/games/progression.ts, noteAnswer), a deck
 * dealt by level would never reach its B1 cards, so the page deals a fixed mix
 * of the three levels (its CARD_MIX).
 *
 * CHECKED ON 31 OCTOBER 2026 by a second reader, every card and every real
 * line against the held text and its chapter (all 35 word for word, in the
 * section given). Three cards changed:
 *   - pleased: its line was "Darcy seemed much pleased with the attention.",
 *     cut from Mr Collins's "Mr. Darcy seemed much pleased...", so it was not
 *     the sentence the book prints, and it is Collins misreading Darcy's
 *     contempt. It is now Elizabeth's "But are you pleased, Jane?" (Chapter 59).
 *   - teacher: the meaning said "whose job is", but its real line is Biddy,
 *     who taught Pip without being paid ("I was your first teacher though"). It
 *     is now "A person who helps others learn, often as their job."
 *   - dentist: "A doctor who looks after your teeth." A dentist is not a
 *     doctor; it is now "A person whose job is to look after people's teeth."
 * The old six topics stay almost all A1 (Actions has no A2 or B1 card;
 * Places, Time and Objects one A2 and no B1), and Work has two A1 cards and
 * Health four: the mix is still dealt in full (5, 5 and 4 a round, all 240
 * met by round 20), but a later pass could add B1 time and action words.
 */

export type Topic =
  | 'People'
  | 'Places'
  | 'Time'
  | 'Actions'
  | 'Feelings'
  | 'Objects'
  | 'Home'
  | 'School'
  | 'Shops'
  | 'Travel'
  | 'Health'
  | 'Work'

export interface VocabCard {
  word: string
  partOfSpeech: string
  simpleDefinition: string
  /** The sentence on the front of the card. */
  exampleSentence: string
  /**
   * The word in a second sentence, on the back of the card, so the meaning is
   * checked in a new place. A real line where `source` says where from.
   */
  sentence: string
  /** Where a real line comes from: a held public-domain text, as printed. */
  source?: string
  topic: Topic
  /** 1 A1, 2 A2, 3 B1 (GameBank.tier). */
  tier: 1 | 2 | 3
  /** Other cards' words that this card's explanation teaches, so the two are dealt apart. */
  also?: string[]
}

