import type { GameBank } from '@/lib/games/explanations/types'

/**
 * Bigger, Biggest: choose the form of an adjective that fits the gap in a
 * sentence: the comparative (smaller, more expensive, better), the
 * superlative (smallest, most expensive, best), or an equal comparison (as
 * tall as, the same as).
 *
 * Moved out of src/app/games/comparatives-superlatives/page.tsx on 16 October
 * 2026, when every answer gained an explanation
 * (src/lib/games/explanations/types.ts).
 *
 * WHAT WAS WRONG WITH THE QUESTIONS (found writing those explanations):
 *
 *   - "Please could you give me a ___ piece of cake?" (far, "further") is not a
 *     comparison: it has no "than", and "a further piece" means "another piece",
 *     not "a piece that is more far". The game asks for the comparative of
 *     "far", so it was testing a different word. It is now "My new school is
 *     ___ from home than my old one.", which is a comparison of distance;
 *   - "Today is ___ than yesterday." is asked twice, for "cool" and for "sunny".
 *     Both stay, and the key of every question now includes its adjective, so
 *     the two can be told apart in a student's saved results;
 *   - "That was the ___ joke of the night." (sad, "saddest") asked learners to
 *     call a joke sad, which makes sense only as slang for a weak joke. The
 *     answer was right, but the sentence it models did not mean what a learner
 *     reads in it. It is now "That was the ___ song of the night." (Found by
 *     the second reader, 16 October 2026.)
 *
 * `family` is the section heading each question sat under on the page, so a
 * student's saved results can say which spelling rule they miss. `rule` is the
 * one-line rule the page used to show after an answer; the explanation panel
 * replaces it, and it is kept here as the record of what the page said.
 *
 * REBUILT FOR DEPTH (24 October 2026). The founder found the games "weak in
 * depth and content"; the audit (.tmp-games-audit/REPORT-eal.md) found that
 * this game offered non-words ("most dangerousest", "safeest"), showed both
 * the adjective and the form wanted ("Make the superlative") before the
 * student answered, and held 64 questions, so that both forms of one
 * adjective met 1.4 times a round. It now holds 243 in three tiers:
 *
 *   - tier 1 (A1), 80: one-syllable adjectives with -er and -est, big and
 *     hot, good and bad, in short everyday sentences and questions ("Is a
 *     train ___ than a bus?");
 *   - tier 2 (A2), 80: the spelling rules (doubling, -e, -y), long
 *     adjectives with "more" and "most", -ed and -ing adjectives, and the
 *     irregulars far and bad;
 *   - tier 3 (B1), 83, all new: fourteen real lines from books out of UK
 *     copyright (Animal Farm, Jane Eyre, Great Expectations, Pride and
 *     Prejudice, Silas Marner, The Sign of Four), each copied word for word
 *     from src/data/full-texts with its chapter in `source`; "as ... as" and
 *     "not as ... as" (13 more); "the same as" (5); reading a short table of
 *     prices, heights, times, distances, weather or a survey to choose the
 *     comparison that is true (18, the badge naming both adjectives where the
 *     table decides between them, as "cheap or expensive"); "much", "far",
 *     "a lot" and "a bit" (6); "one of the" and "the second" (5);
 *     superlatives with "ever" (5); -ed adjectives against their -ing pair
 *     (6); adverbs (5 more); and turns in a dialogue (6), "less" among them.
 *
 * The page no longer says which form is wanted: the sentence decides. It
 * shows an item's `context` above the sentence and its `source` under it.
 *
 * THE OPTIONS. Each question carries its own wrong options (`wrong`), each a
 * mistake learners make: the other form, "more" or "most" before a short
 * adjective, the comparison made twice ("more bigger", "most biggest"), the
 * plain adjective before "than", a spelling rule forgotten ("biger",
 * "happyer"), -er or -est on a long adjective ("expensiver", as German and
 * Dutch speakers say it), the regular form of an irregular adjective
 * ("gooder", "badder", "worser"), the adjective for the adverb ("more
 * careful" for "more carefully"), the -ing word for the -ed one ("more
 * boring" for "more bored"), and in "as ... as", "bigger as" and "as big
 * than". distractorCandidates(), which built the options by rule and so
 * produced "expensiveer", "largeest" and "most dangerousest", is gone.
 * Options that could be argued right were left out: "more" or "most" before
 * a short adjective that some speakers do compare that way (clean, kind,
 * fresh, cool, safe, close, rude, strange, sad, fit), the comparative after
 * "one of the" ("one of the older cities" is good English), the plain
 * adjective in a superlative frame ("the expensive phone in the shop"),
 * "farther" beside "further", and any "Which is ___, A or B?" question,
 * where many speakers use the superlative for two. So 25 questions have two
 * wrong options, not three.
 *
 * Existing questions fixed:
 *   - "A lorry is ___ than a bicycle." (slow) said something untrue, since a
 *     lorry is the faster; it is now "A tortoise is ___ than a rabbit.";
 *   - "The Nile is one of the ___ rivers on Earth." offered "longer", and
 *     "one of the longer rivers" is good English; it no longer does;
 *   - "This is the ___ chair in the room." (comfortable) is now "... in the
 *     shop.": a room may hold two chairs, and then "the more comfortable
 *     chair" is right too;
 *   - "This is the ___ lift in the building." (slow) and "That shop is the
 *     ___ one from here." (far) no longer offer "slower" and "further", which
 *     are right where there are only two lifts or two shops;
 *   - every question lost its form label and had its options replaced, so
 *     every explanation was rewritten.
 * Nothing was removed.
 *
 * FACTS AND GROUPS. No two questions about one adjective share a round
 * (BANK.facts: both adjectives of a table question, and the adjective behind
 * an adverb, as careful behind carefully), nor two with the same sentence.
 * No explanation names another question's answer unless the two share a
 * fact. `family` is still the rule a question tests and what the page
 * records; the dealer spreads the families through a round (BANK.tag).
 *
 * CHECKED BY A SECOND READER (31 October 2026), every question and its
 * explanation. Fixed:
 *   - "She was the ___ of all the parents." (worried) had a second right
 *     answer: "she was the most worrying of all the parents" is good
 *     English, meaning she gave the others most cause to worry. It is now
 *     "Of everyone in the family, Dad was the ___ about the long journey.",
 *     where "worried about" leaves only the -ed form;
 *   - "Leo is ___ Ali. They were both born in 2013." told a child that two
 *     people born in one year are the same age, which is not true for most
 *     of it. It is now "They are both twelve.";
 *   - "Your answer is ___ mine, so we must both be right." modelled a false
 *     step, since two answers that match can both be wrong. It is now "We
 *     both wrote 42.";
 *   - "She sings ___ than anyone in the choir." compared her with herself,
 *     since she is in the choir. It is now "than anyone else in the choir";
 *   - "Model A is ___ Model B." offered "less expensiver than", two mistakes
 *     at once that learners do not make: a learner who writes "less" has
 *     already chosen the pattern with a separate word. It now offers "less
 *     expensive as", the "as" for "than" mistake the bank tests elsewhere.
 * The 34 other options that put -er or -est on an adjective taking "more"
 * and "most" ("expensivest", "moderner", "dangerousest") were kept: it is a
 * recorded learner error, not an invention. A study of learners' essays (J.
 * Subajana, Journal of Business Management, Vavuniya Campus of the
 * University of Jaffna, June 2020) found that they "extended the
 * monosyllabic rules" to longer adjectives, and records "dangerousest"; the
 * work it cites found learners adding -er and -est "to all adjectives
 * indiscriminately"; English-teaching materials give "expensivest" and
 * "beautifullest" as typical mistakes; and German, Dutch, Polish, Russian
 * and Arabic, all spoken by EAL pupils here, make the comparative of a long
 * adjective with an ending.
 */

export type Form = 'comparative' | 'superlative' | 'equal'

/** The rule the question tests: a spelling rule, or for tier 3 the pattern. */
export type Family =
  | 'short-adjectives'
  | 'double-consonant'
  | 'ends-in-e'
  | 'ends-in-y'
  | 'long-adjectives'
  | 'irregular'
  | 'ed-adjectives'
  | 'adverbs'
  | 'as-as'
  | 'the-same-as'
  | 'reading-a-table'

export interface CompItem {
  /** Contains ___ for the gap. */
  sentence: string
  /**
   * A short text read before the sentence (a price list, a table of heights,
   * a weather report), shown above it. Its lines are separated by newlines.
   */
  context?: string
  /** Where a real line comes from, as the held text titles it, shown under it. */
  source?: string
  /** What the badge beside the sentence shows: the adjective, or two of them. */
  adjective: string
  answer: string
  /** The wrong options shown with the answer, each a mistake learners make. */
  wrong: string[]
  form: Form
  rule: string
  family: Family
  /** 1 for A1, 2 for A2, 3 for B1. */
  tier: 1 | 2 | 3
  /** Anything else no other question in the round may share (a word family). */
  facts?: string[]
}

