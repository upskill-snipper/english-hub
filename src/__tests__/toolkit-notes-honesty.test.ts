/**
 * What a learner is told about their own revision notes.
 *
 * Two defects, both in the printed document rather than on the screen:
 *
 *   1. The deterministic template - which runs on every model failure, and
 *      ran for every request during the retired-model outage - footed itself
 *      "Generated by The English Hub AI Toolkit". The one honest signal, the
 *      "Template-Based" badge, was print:hidden, so the PDF a 14-16 year old
 *      revises from claimed authorship the product did not have.
 *
 *   2. For any topic that is not one of our set texts, the same template
 *      asserted an author ("the writer"), four themes (Power, Responsibility,
 *      Social Class, Morality) and a section of character analysis. The
 *      revision builder offers 32 such topics. It served the same invented
 *      theme list for the set texts that carry no keyThemes in our index.
 *
 * These tests hold both closed, and they hold the consent gate on the route
 * closed while doing it.
 */

