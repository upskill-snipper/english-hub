// ── The topics the UI actually offers ──────────────────────────────────────
// Read from the page source rather than restated here, so a topic added to
// the dropdown cannot escape these checks.
function uiTopics(): string[] {
  const src = readFileSync(join(ROOT, 'src/app/toolkit/revision-builder/page.tsx'), 'utf8')
  const values = [...src.matchAll(/<option value="([^"]+)"/g)].map((m) => m[1])
  return [...new Set(values)]
}

/**
 * The exact phrases the old template produced when it had no author: it
 * printed "the writer" into the author field and then wrote sentences about
 * that non-existent person. Generic exam advice about "the writer's methods"
 * is legitimate and is not caught here.
 */
const FABRICATED_AUTHOR_PHRASES = [
  '**Author:** the writer',
  'the writer explores this',
  'does the writer use to present',
  'does the writer organise',
  'how the writer presents them',
]

function isSetText(topic: string): boolean {
  return SET_TEXTS.some((t) => t.title.toLowerCase() === topic.toLowerCase() || t.slug === topic)
}

describe('the notes template invents nothing', () => {
  const nonSetTextTopics = uiTopics().filter((t) => !isSetText(t))

  it('the revision builder really does offer topics that are not set texts', () => {
    // 12 Language Topics + 10 Creative Writing + 10 Exam Technique.
    expect(nonSetTextTopics.length).toBeGreaterThanOrEqual(12)
  })

  it.each(nonSetTextTopics)('"%s" gets no invented author, themes or characters', (topic) => {
    const notes = generateTemplateNotes(topic, 'aqa', 6, [])

    expect(notes).not.toMatch(/\*\*Author:\*\*/)
    // The old placeholder author. "the writer's methods" as generic exam
    // advice is fine; an invented author of this topic is not.
    for (const fabricated of FABRICATED_AUTHOR_PHRASES) {
      expect(notes).not.toContain(fabricated)
    }
    expect(notes).not.toMatch(/is a central theme/i)
    expect(notes).not.toMatch(/## Key Themes/)
    expect(notes).not.toMatch(/## Characters & Relationships/)
    for (const invented of ['Responsibility', 'Social Class', 'Morality']) {
      expect(notes).not.toContain(`### 1. ${invented}`)
    }
    // ... and says plainly that we hold nothing text-specific for it.
    expect(notes).toContain('does not hold verified subject content')
    expect(notes).toContain('general exam technique only')
  })

  it('a skills topic is never labelled with a text type', () => {
    const notes = generateTemplateNotes('Creative Writing', 'aqa', 5, [])
    expect(notes).not.toMatch(/\*\*Type:\*\*/)
    expect(notes).not.toContain('Poetry')
  })

  it.each(SET_TEXTS.map((t) => [t.title, t] as const))(
    '"%s" is described only from the set-text index',
    (_title, text) => {
      const notes = generateTemplateNotes(text.title, 'aqa', 7, [])

      expect(notes).toContain(`**Author:** ${text.author}`)
      expect(notes).toContain(`**Type:** ${CATEGORY_LABELS[text.category]}`)
      for (const fabricated of FABRICATED_AUTHOR_PHRASES) {
        expect(notes).not.toContain(fabricated)
      }
      expect(notes).not.toMatch(/is a central theme/i)

      if (text.keyThemes && text.keyThemes.length > 0) {
        for (const theme of text.keyThemes) expect(notes).toContain(theme)
      } else {
        // No verified themes: say so rather than serve the old invented four.
        expect(notes).toContain('does not yet hold a verified theme list')
        expect(notes).not.toMatch(/^### \d+\. /m)
      }
    },
  )

  it('a prose or non-fiction set text is not printed to a learner as poetry', () => {
    const mislabelCandidates = SET_TEXTS.filter(
      (t) => t.category === 'prose' || t.category === 'non-fiction',
    )
    expect(mislabelCandidates.length).toBeGreaterThan(0)
    for (const text of mislabelCandidates) {
      const notes = generateTemplateNotes(text.title, 'aqa', 5, [])
      expect(notes).not.toContain('**Type:** Poetry')
    }
  })

  it('keeps the learner-supplied weak areas it was given, and nothing else', () => {
    const notes = generateTemplateNotes('Vocabulary', 'aqa', 5, ['Unseen Poetry'])
    expect(notes).toContain('**Unseen Poetry**')
  })
})

describe('provenance in the printed document', () => {
  it('the template footer does not claim AI authorship', () => {
    const footer = notesProvenanceFooter('template')
    expect(footer).toContain('NOT AI-generated')
    expect(footer).not.toContain('Generated by The English Hub AI Toolkit')
  })

  it('the AI footer names the provider actually used', () => {
    const footer = notesProvenanceFooter('ai')
    expect(footer).toContain('Anthropic')
    expect(footer).not.toMatch(/OpenAI/i)
  })

  it('no code path can still emit the old AI Toolkit footer', () => {
    const src = readFileSync(
      join(ROOT, 'src/app/api/toolkit/generate-notes/notes-template.ts'),
      'utf8',
    )
    const inStringLiteral = src
      .split('\n')
      .filter((l) => !l.trimStart().startsWith('*') && !l.trimStart().startsWith('//'))
      .join('\n')
    expect(inStringLiteral).not.toContain('Generated by The English Hub AI Toolkit')
  })

  it('the on-page provenance badge is printed, not print:hidden', () => {
    const src = readFileSync(join(ROOT, 'src/app/toolkit/revision-builder/page.tsx'), 'utf8')
    const badgeAt = src.indexOf("{aiGenerated ? 'AI-Generated' : 'Template-Based'}")
    expect(badgeAt).toBeGreaterThan(-1)

    // The container element immediately above the badge must not be hidden
    // from print - that is exactly how the honest label used to disappear
    // from the PDF.
    const containerStart = src.lastIndexOf('<div', badgeAt)
    const container = src.slice(containerStart, badgeAt)
    expect(container).not.toContain('print:hidden')

    // Nor may the AI disclosure panel be hidden from print.
    expect(src).not.toContain('<AiGeneratedNotice variant="panel" className="print:hidden" />')
  })
})

describe('POST /api/toolkit/generate-notes', () => {
  it('serves the template honestly when no model is configured', async () => {
    const { status, json } = await postNotes({
      board: 'aqa',
      topic: 'Creative Writing',
      targetGrade: 6,
    })

    expect(status).toBe(200)
    expect(json.metadata.aiGenerated).toBe(false)
    expect(json.metadata.source).toBe('template')
    expect(json.notes).toContain('NOT AI-generated')
    expect(json.notes).not.toContain('Generated by The English Hub AI Toolkit')
    expect(json.notes).not.toMatch(/is a central theme/i)
  })

  it('still calls the template honest when the model fails mid-request', async () => {
    // The outage case: a key is present, so the old code labelled the
    // response AI-generated, and the template footed itself as AI work.
    process.env.ANTHROPIC_API_KEY = 'sk-test'
    vi.stubGlobal('fetch', vi.fn().mockRejectedValue(new Error('upstream down')))

    const { status, json } = await postNotes({ board: 'aqa', topic: 'Macbeth', targetGrade: 7 })

    expect(status).toBe(200)
    expect(json.metadata.aiGenerated).toBe(false)
    expect(json.metadata.source).toBe('template')
    expect(json.notes).toContain('NOT AI-generated')
    expect(json.notes).not.toContain('written for you by an AI model')
  })

  it('labels genuine model output as AI work and names the provider', async () => {
    process.env.ANTHROPIC_API_KEY = 'sk-test'
    vi.stubGlobal(
      'fetch',
      vi.fn().mockResolvedValue({
        ok: true,
        json: async () => ({
          content: [{ text: '# Revision Notes: Macbeth\n\nModel-written body.' }],
          usage: { input_tokens: 10, output_tokens: 20 },
        }),
      }),
    )

    const { status, json } = await postNotes({ board: 'aqa', topic: 'Macbeth', targetGrade: 7 })

    expect(status).toBe(200)
    expect(json.metadata.aiGenerated).toBe(true)
    expect(json.metadata.source).toBe('ai')
    expect(json.notes).toContain('Model-written body.')
    expect(json.notes).toContain("written for you by an AI model (Anthropic's Claude)")
    expect(json.notes).not.toContain('NOT AI-generated')
  })

  it('refuses a minor without verified guardian AI consent, and returns no notes', async () => {
    mockCheckMinorAIConsent.mockResolvedValue({
      allowed: false,
      reason: 'AI_PROCESSING_REQUIRED',
    })

    const { status, json } = await postNotes({ board: 'aqa', topic: 'Macbeth', targetGrade: 7 })

    expect(status).toBe(403)
    expect(json.notes).toBeUndefined()
    expect(json.error).toBe('AI_PROCESSING_REQUIRED')
  })

  it('refuses an account that has opted out of AI, and returns no notes', async () => {
    mockIsAiOptedOut.mockResolvedValue(true)

    const { status, json } = await postNotes({ board: 'aqa', topic: 'Macbeth', targetGrade: 7 })

    expect(status).toBe(403)
    expect(json.notes).toBeUndefined()
  })
})
