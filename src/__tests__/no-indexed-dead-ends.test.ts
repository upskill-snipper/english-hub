import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { getAllPrintables, isPublished } from '@/lib/printables/list'
import { getAllLessonPlans, isLessonPlanPublished } from '@/lib/lesson-plans/list'

/**
 * Sixty indexed pages promising content that does not exist (CUI-7).
 *
 * THE DEFECT (19 September 2026). Twenty printables, twenty lesson plans and
 * twenty EAL skill pages were all fully indexable and all listed in the
 * sitemap. Not one of them had anything on it: every printable carried
 * `status: 'coming-soon'` and none had a `pdfUrl`, every lesson plan was
 * `coming-soon`, and the EAL listening and reading routes render a placeholder
 * card and nothing else.
 *
 * Worse than thin, the EAL pages carried a specific false promise: "being
 * generated by the local AI wave pipeline. Check back in 6-48 hours." The
 * script named in both file headers, `generate_eal_skill_band.py`, does not
 * exist anywhere in this repository and there is no EAL generation script at
 * all. Nobody was generating anything, and the page told every visitor - in
 * English and in Arabic - to come back within two days.
 *
 * WHAT THIS DELIBERATELY DOES NOT DO. The obvious next step is to flip a
 * printable to `available`. It must not happen yet: `pdfUrl` is read in
 * exactly one place in the entire repo - the badge condition - and the
 * 184-line detail page has no anchor, button or download control bound to it.
 * Marking one available would re-admit it to the sitemap labelled "Available"
 * with no way to get the file: the same dead end, wearing a better badge. The
 * download control has to come first.
 */

const ROOT = process.cwd()

function code(rel: string): string {
  return readFileSync(join(ROOT, rel), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split(/\r?\n/)
    .map((l) => l.replace(/\/\/.*$/, ''))
    .join('\n')
}

// ─── The false promise ──────────────────────────────────────────────────────

describe('the EAL placeholder pages', () => {
  const PAGES = ['src/app/eal/[slug]/listening/page.tsx', 'src/app/eal/[slug]/reading/page.tsx']

  it.each(PAGES)('%s promises no timescale it cannot keep', (rel) => {
    const body = code(rel)
    expect(body).not.toMatch(/6-48/)
    expect(body).not.toMatch(/wave pipeline/i)
    expect(body).not.toMatch(/being generated/i)
    // Arabic twin of the same promise.
    expect(body).not.toMatch(/ساعة/)
  })

  it.each(PAGES)('%s states plainly that nothing is published', (rel) => {
    // Not "coming soon", which implies work in progress that nobody is doing.
    expect(code(rel)).toMatch(/We have not published/)
  })

  it.each(PAGES)('%s asks search engines not to index it', (rel) => {
    expect(code(rel)).toMatch(/robots: \{ index: false, follow: false \}/)
  })

  it.each(PAGES)('%s no longer cites a script that does not exist', (rel) => {
    // The header named generate_eal_skill_band.py as the thing that would fill
    // these pages in. It is not in this repo and never was.
    const raw = readFileSync(join(ROOT, rel), 'utf8')
    const claimsItRuns = /generate_eal_skill_band\.py\n \* fills/.test(raw)
    expect(claimsItRuns).toBe(false)
  })
})

// ─── The two skill pages that ARE real must stay indexed ────────────────────

describe('the EAL skill pages that are built', () => {
  it.each(['writing', 'speaking'])('%s is not de-indexed by mistake', (skill) => {
    // Both delegate to CEFRAssessClient and are genuine. Only their file
    // headers still mention the old stub, which is why a careless sweep would
    // have caught them.
    const body = code(`src/app/eal/[slug]/${skill}/page.tsx`)
    expect(body).not.toMatch(/robots: \{ index: false/)
  })
})

// ─── One predicate, four consumers ──────────────────────────────────────────

describe('what counts as published', () => {
  it('a printable needs a real PDF, not just a status', async () => {
    // The index card used to ask only about status. A printable flipped to
    // `available` before its PDF landed read "Available" there and "Coming
    // soon" on its own page - and printables ship one at a time, so that is
    // the normal intermediate state.
    expect(isPublished({ status: 'available', pdfUrl: '/x.pdf' })).toBe(true)
    expect(isPublished({ status: 'available', pdfUrl: undefined })).toBe(false)
    expect(isPublished({ status: 'coming-soon', pdfUrl: '/x.pdf' })).toBe(false)
  })

  it('is used by the index card and the detail page alike', () => {
    expect(code('src/app/resources/teaching/printables/page.tsx')).toContain('isPublished(')
    expect(code('src/app/resources/teaching/printables/[slug]/page.tsx')).toContain('isPublished(')
    // The looser check is gone.
    expect(code('src/app/resources/teaching/printables/page.tsx')).not.toMatch(
      /const comingSoon = printable\.status === 'coming-soon'/,
    )
  })

  it('reflects the corpus as it actually stands today', async () => {
    // Honest baseline: if someone publishes one, this number moves and the
    // assertion below has to be looked at rather than silently drifting.
    const printables = await getAllPrintables()
    expect(printables.length).toBeGreaterThan(15)
    expect(printables.filter(isPublished)).toEqual([])

    const plans = getAllLessonPlans()
    expect(plans.length).toBeGreaterThan(15)
    expect(plans.filter(isLessonPlanPublished)).toEqual([])
  })
})

// ─── The dead ends are out of the sitemap ───────────────────────────────────

describe('the sitemap', () => {
  it('filters both libraries by the published predicate', () => {
    const body = code('src/app/sitemap.ts')
    expect(body).toMatch(/getAllLessonPlans\(\)\.filter\(isLessonPlanPublished\)/)
    expect(body).toMatch(/\.filter\(isPublished\)/)
    // The unconditional slug loop is gone.
    expect(body).not.toMatch(/for \(const slug of await getPrintableSlugs\(\)\)/)
  })

  it('lists only the EAL skills that exist', () => {
    const body = code('src/app/sitemap.ts')
    expect(body).toMatch(/for \(const skill of \['writing', 'speaking'\]\)/)
    expect(body).not.toMatch(/'reading', 'writing', 'listening', 'speaking'/)
  })
})

// ─── The real sitemap output, not just its source ───────────────────────────

describe('the generated sitemap', () => {
  it('contains no dead end at all', async () => {
    const { default: sitemap } = await import('@/app/sitemap')
    const entries = await sitemap()
    // Entry urls are absolute; compare on the path or this passes vacuously
    // whatever the filter does.
    const paths = new Set(entries.map((e) => e.url.replace('https://theenglishhub.app', '') || '/'))
    expect(paths.size).toBeGreaterThan(50)

    const offenders: string[] = []
    for (const p of await getAllPrintables()) {
      const path = `/resources/teaching/printables/${p.slug}`
      if (paths.has(path) !== isPublished(p)) offenders.push(path)
    }
    for (const plan of getAllLessonPlans()) {
      const path = `/resources/teaching/lesson-plans/${plan.slug}`
      if (paths.has(path) !== isLessonPlanPublished(plan)) offenders.push(path)
    }
    for (const suffix of ['/listening', '/reading']) {
      for (const path of paths) {
        if (path.startsWith('/eal/') && path.endsWith(suffix)) offenders.push(path)
      }
    }
    expect(offenders).toEqual([])
  })
})
